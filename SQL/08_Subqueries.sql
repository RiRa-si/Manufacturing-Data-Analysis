-- Q1. FIND MANUFACTURING RECORDS WITH VIBRATION ABOVE THE OVERALL AVERAGE.

SELECT
    MACHINE_ID,
    MACHINE_TYPE,
    VIBRATION_RMS,
    RPM
FROM MANUFACTURING_DATA
WHERE VIBRATION_RMS > (
    SELECT AVG(VIBRATION_RMS)
    FROM MANUFACTURING_DATA
)
ORDER BY VIBRATION_RMS DESC;

-- Q2. FIND MACHINE TYPES WITH ABOVE-AVERAGE MOTOR TEMPERATURE.

SELECT
    MACHINE_TYPE,
    ROUND(AVG(TEMPERATURE_MOTOR), 2) AS AVG_TEMPERATURE
FROM MANUFACTURING_DATA
GROUP BY MACHINE_TYPE
HAVING AVG(TEMPERATURE_MOTOR) > (
    SELECT AVG(TEMPERATURE_MOTOR)
    FROM MANUFACTURING_DATA
)
ORDER BY AVG_TEMPERATURE DESC;

-- Q3. FIND MANUFACTURING RECORDS WITH THE MAXIMUM RPM VALUE.

SELECT
    MACHINE_ID,
    MACHINE_TYPE,
    RPM,
    VIBRATION_RMS,
    OPERATING_MODE
FROM MANUFACTURING_DATA
WHERE RPM = (
    SELECT MAX(RPM)
    FROM MANUFACTURING_DATA
);

-- Q4. FIND MACHINES THAT HAVE AT LEAST ONE POSITIVE FAILURE LABEL.

SELECT DISTINCT
    MACHINE_ID,
    MACHINE_TYPE
FROM MANUFACTURING_DATA
WHERE MACHINE_ID IN (
    SELECT MACHINE_ID
    FROM MANUFACTURING_DATA
    WHERE FAILURE_WITHIN_24H = 1
)
ORDER BY MACHINE_ID;

-- Q5. FIND MACHINE TYPES WITH ABOVE-AVERAGE POSITIVE FAILURE RECORDS.

SELECT
    MACHINE_TYPE,
    COUNT(*) AS FAILURE_RECORDS
FROM MANUFACTURING_DATA
WHERE FAILURE_WITHIN_24H = 1
GROUP BY MACHINE_TYPE
HAVING COUNT(*) > (
    SELECT AVG(FAILURE_COUNT)
    FROM (
        SELECT
            MACHINE_TYPE,
            COUNT(*) AS FAILURE_COUNT
        FROM MANUFACTURING_DATA
        WHERE FAILURE_WITHIN_24H = 1
        GROUP BY MACHINE_TYPE
    ) AS MACHINE_FAILURES
)
ORDER BY FAILURE_RECORDS DESC;

