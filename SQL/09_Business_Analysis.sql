-- Q1. IDENTIFY THE MACHINE TYPE WITH THE HIGHEST POSITIVE FAILURE RATE.

SELECT
    MACHINE_TYPE,
    COUNT(*) AS TOTAL_RECORDS,
    SUM(CASE
        WHEN FAILURE_WITHIN_24H = 1 THEN 1
        ELSE 0
    END) AS FAILURE_RECORDS,
    ROUND(
        SUM(CASE
            WHEN FAILURE_WITHIN_24H = 1 THEN 1
            ELSE 0
        END) * 100.0 / COUNT(*),
        2
    ) AS FAILURE_RATE_PERCENT
FROM MANUFACTURING_DATA
GROUP BY MACHINE_TYPE
ORDER BY FAILURE_RATE_PERCENT DESC;


