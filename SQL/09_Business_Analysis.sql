-- Q4. IDENTIFY FAILURE TYPES WITH THE HIGHEST NUMBER OF RECORDS.

SELECT
    FAILURE_TYPE,
    COUNT(*) AS TOTAL_RECORDS,
    ROUND(
        COUNT(*) * 100.0 / (
            SELECT COUNT(*)
            FROM MANUFACTURING_DATA
            WHERE FAILURE_TYPE <> 'NONE'
        ),
        2
    ) AS FAILURE_TYPE_PERCENT
FROM MANUFACTURING_DATA
WHERE FAILURE_TYPE <> 'NONE'
GROUP BY FAILURE_TYPE
ORDER BY TOTAL_RECORDS DESC;


-- Q5. IDENTIFY MACHINES WITH THE HIGHEST AVERAGE ESTIMATED REPAIR COST.

SELECT
    MACHINE_ID,
    MACHINE_TYPE,
    COUNT(*) AS TOTAL_RECORDS,
    ROUND(AVG(ESTIMATED_REPAIR_COST), 2) AS AVG_REPAIR_COST
FROM MANUFACTURING_DATA
GROUP BY
    MACHINE_ID,
    MACHINE_TYPE
ORDER BY AVG_REPAIR_COST DESC
LIMIT 10;


-- Q6. COMPARE AVERAGE SENSOR READINGS BY OPERATING MODE.

SELECT
    OPERATING_MODE,
    COUNT(*) AS TOTAL_RECORDS,
    ROUND(AVG(TEMPERATURE_MOTOR), 2) AS AVG_TEMPERATURE,
    ROUND(AVG(VIBRATION_RMS), 2) AS AVG_VIBRATION,
    ROUND(AVG(RPM), 2) AS AVG_RPM
FROM MANUFACTURING_DATA
GROUP BY OPERATING_MODE
ORDER BY AVG_TEMPERATURE DESC;


