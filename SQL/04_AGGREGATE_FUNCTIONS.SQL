-- Q1. COUNT THE TOTAL NUMBER OF MANUFACTURING RECORDS.

SELECT COUNT(*) AS TOTAL_RECORDS
FROM MANUFACTURING_DATA;


-- Q2. CALCULATE THE TOTAL ESTIMATED REPAIR COST.

SELECT SUM(ESTIMATED_REPAIR_COST) AS TOTAL_ESTIMATED_REPAIR_COST
FROM MANUFACTURING_DATA;


-- Q3. CALCULATE THE AVERAGE MOTOR TEMPERATURE.

SELECT AVG(TEMPERATURE_MOTOR) AS AVERAGE_MOTOR_TEMPERATURE
FROM MANUFACTURING_DATA;

SELECT * FROM MANUFACTURING_DATA;


-- Q4. FIND THE HIGHEST MOTOR TEMPERATURE.

SELECT MAX(TEMPERATURE_MOTOR) AS HIGHEST_MOTOR_TEMPERATURE
FROM MANUFACTURING_DATA;


-- Q5. FIND THE LOWEST MOTOR TEMPERATURE.

SELECT MIN(TEMPERATURE_MOTOR) AS LOWEST_MOTOR_TEMPERATURE
FROM MANUFACTURING_DATA;


-- Q6. CALCULATE THE AVERAGE VIBRATION
-- AND ROUND IT TO TWO DECIMAL PLACES.

SELECT ROUND(AVG(VIBRATION_RMS), 2) AS AVERAGE_VIBRATION
FROM MANUFACTURING_DATA;



-- Q7. CALCULATE MULTIPLE RPM STATISTICS.

SELECT
    COUNT(RPM) AS TOTAL_RPM_RECORDS,
    ROUND(AVG(RPM), 2) AS AVERAGE_RPM,
    MAX(RPM) AS HIGHEST_RPM,
    MIN(RPM) AS LOWEST_RPM
FROM MANUFACTURING_DATA;



-- Q8. CALCULATE THE AVERAGE ESTIMATED REPAIR COST.
-- ROUND THE RESULT TO TWO DECIMAL PLACES.

SELECT ROUND(AVG(ESTIMATED_REPAIR_COST), 2) AS AVERAGE_ESTIMATED_REPAIR_COST
FROM MANUFACTURING_DATA;
