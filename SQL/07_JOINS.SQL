-- STEP 1. CREATE A MACHINE REFERENCE TABLE.

CREATE TABLE MACHINE_REFERENCE AS
SELECT DISTINCT
    MACHINE_ID,
    MACHINE_TYPE
FROM MANUFACTURING_DATA;

-- STEP 2. DISPLAY ALL MACHINE REFERENCE RECORDS.

SELECT *
FROM MACHINE_REFERENCE
ORDER BY MACHINE_ID;

-- Q1. DISPLAY MANUFACTURING RECORDS WITH MACHINE DETAILS USING INNER JOIN.

SELECT M.MACHINE_ID , M.MACHINE_TYPE , A.RPM , A.VIBRATION_RMS
FROM MACHINE_REFERENCE AS M
INNER JOIN manufacturing_data AS A
ON M.MACHINE_ID = A.MACHINE_ID 
LIMIT 20;



-- Q2. DISPLAY ALL MANUFACTURING RECORDS AND MATCHING MACHINE DETAILS USING LEFT JOIN.

SELECT
    A.MACHINE_ID,
    A.RPM,
    A.VIBRATION_RMS,
    M.MACHINE_TYPE
FROM MANUFACTURING_DATA AS A
LEFT JOIN MACHINE_REFERENCE AS M
ON A.MACHINE_ID = M.MACHINE_ID
LIMIT 20;

-- Q3. DISPLAY ALL MACHINE REFERENCE RECORDS AND MATCHING MANUFACTURING DETAILS USING RIGHT JOIN.

SELECT
    A.MACHINE_ID,
    M.MACHINE_TYPE,
    A.RPM,
    A.VIBRATION_RMS
FROM MANUFACTURING_DATA AS A
RIGHT JOIN MACHINE_REFERENCE AS M
ON A.MACHINE_ID = M.MACHINE_ID
LIMIT 20;

-- Q4. DISPLAY MANUFACTURING RECORDS WITH VIBRATION ABOVE 3.0 USING INNER JOIN.

SELECT
    A.MACHINE_ID,
    M.MACHINE_TYPE,
    A.VIBRATION_RMS,
    A.RPM
FROM MANUFACTURING_DATA AS A
INNER JOIN MACHINE_REFERENCE AS M
ON A.MACHINE_ID = M.MACHINE_ID
WHERE A.VIBRATION_RMS > 3.0
LIMIT 20;

-- Q5. CALCULATE THE TOTAL MANUFACTURING RECORDS FOR EACH MACHINE TYPE USING INNER JOIN.

SELECT
    M.MACHINE_TYPE,
    COUNT(*) AS TOTAL_RECORDS
FROM MANUFACTURING_DATA AS A
INNER JOIN MACHINE_REFERENCE AS M
ON A.MACHINE_ID = M.MACHINE_ID
GROUP BY M.MACHINE_TYPE
ORDER BY TOTAL_RECORDS DESC;

-- Q6. COUNT RECORDS FOR EACH MACHINE TYPE AND FAILURE LABEL USING INNER JOIN.

SELECT
    M.MACHINE_TYPE,
    A.FAILURE_WITHIN_24H,
    COUNT(*) AS TOTAL_RECORDS
FROM MANUFACTURING_DATA AS A
INNER JOIN MACHINE_REFERENCE AS M
ON A.MACHINE_ID = M.MACHINE_ID
GROUP BY
    M.MACHINE_TYPE,
    A.FAILURE_WITHIN_24H
ORDER BY
    M.MACHINE_TYPE,
    A.FAILURE_WITHIN_24H;
    
-- STEP 1. OPERATING MODE REFERENCE TABLE.

CREATE TABLE OPERATING_MODE_REFERENCE AS
SELECT DISTINCT
    OPERATING_MODE
FROM MANUFACTURING_DATA;

-- Q7. ANALYZE AVERAGE RPM AND VIBRATION FOR EACH MACHINE TYPE AND OPERATING MODE USING MULTIPLE JOINS.

SELECT
    M.MACHINE_TYPE,
    O.OPERATING_MODE,
    ROUND(AVG(A.RPM), 2) AS AVG_RPM,
    ROUND(AVG(A.VIBRATION_RMS), 2) AS AVG_VIBRATION
FROM MANUFACTURING_DATA AS A
INNER JOIN MACHINE_REFERENCE AS M
ON A.MACHINE_ID = M.MACHINE_ID
INNER JOIN OPERATING_MODE_REFERENCE AS O
ON A.OPERATING_MODE = O.OPERATING_MODE
GROUP BY
    M.MACHINE_TYPE,
    O.OPERATING_MODE
ORDER BY
    M.MACHINE_TYPE,
    O.OPERATING_MODE;
    

-- Q8. IDENTIFY THE TOP 10 MACHINES WITH THE HIGHEST NUMBER OF POSITIVE FAILURE LABELS USING INNER JOIN.

SELECT
    A.MACHINE_ID,
    M.MACHINE_TYPE,
    COUNT(*) AS FAILURE_RECORDS
FROM MANUFACTURING_DATA AS A
INNER JOIN MACHINE_REFERENCE AS M
ON A.MACHINE_ID = M.MACHINE_ID
WHERE A.FAILURE_WITHIN_24H = 1
GROUP BY
    A.MACHINE_ID,
    M.MACHINE_TYPE
ORDER BY FAILURE_RECORDS DESC
LIMIT 10;
