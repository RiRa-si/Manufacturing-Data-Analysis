-- Q5. CLASSIFY MOTOR TEMPERATURE INTO LOW, MODERATE, ELEVATED, AND VERY HIGH CATEGORIES.
SELECT MACHINE_ID , TEMPERATURE_MOTOR , 
CASE 
   WHEN TEMPERATURE_MOTOR >= 70 THEN "VERY HIGH"
   WHEN TEMPERATURE_MOTOR >= 50 THEN "ELEVATED"
   WHEN TEMPERATURE_MOTOR >= 40 THEN "MODERATE"
   ELSE "LOW"
END AS TEMPERATURE_STATUS
FROM manufacturing_data
LIMIT 20;

