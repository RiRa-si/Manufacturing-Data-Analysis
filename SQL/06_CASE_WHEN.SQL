-- Q1. CATEGORIZE MOTOR TEMPERATURE INTO LOW, NORMAL, AND HIGH LEVELS.

SELECT MACHINE_ID , TEMPERATURE_MOTOR,
CASE 
    WHEN TEMPERATURE_MOTOR >=60 THEN "hIGH"
    WHEN TEMPERATURE_MOTOR >=40 THEN "NORMAL"
    ELSE "LOW"
END AS TEMPERATURE_CATEGORY
FROM MANUFACTURING_DATA
LIMIT 20;

-- Q2. CATEGORIZE VIBRATION LEVELS INTO LOW, NORMAL, AND HIGH.
SELECT MACHINE_ID , VIBRATION_RMS ,
CASE 
   WHEN VIBRATION_RMS >= 3.0 THEN "HIGH"
   WHEN VIBRATION_RMS >= 1.0 THEN "NORMAL"
   ELSE "LOW"
END AS VIBRATION_CATEGORY 
FROM manufacturing_data
LIMIT 20;

-- Q3. CATEGORIZE MACHINE RPM INTO LOW, NORMAL, AND HIGH SPEED LEVELS.
SELECT MACHINE_ID , RPM , 
CASE
   WHEN RPM >=1500 THEN "HIGH"
   WHEN RPM >=500 THEN "NORMAL"
   ELSE "LOW"
END AS RPM_CATEGORY
FROM manufacturing_data
LIMIT 20;

-- Q4. CREATE FAILURE STATUS LABELS USING CASE WHEN.
SELECT 
     MACHINE_ID ,
     FAILURE_WITHIN_24H,
CASE 
   WHEN FAILURE_WITHIN_24H = 1 THEN "FAILURE EXPECTED"
   ELSE "NO FAILURE EXPECTED"
END AS FAILURE_STATUS
FROM MANUFACTURING_DATA 
LIMIT 20;

